from datetime import datetime
from pathlib import Path

import pytest

pytest.importorskip("ecoscope_workflows_ext_custom")  # only present in the ext-custom env

import pandas as pd  # noqa: E402
from docx import Document  # noqa: E402
from ecoscope.platform.tasks.filter import TimeRange, TimezoneInfo  # noqa: E402
from ecoscope_workflows_ext_custom.tasks.results import (  # noqa: E402
    ImageContextItem,
    ImageListContextItem,
    TableContextItem,
    TableListContextItem,
    TemplateContext,
    TextContextItem,
    TimeRangeContextItem,
    create_docx,
)
from PIL import Image  # noqa: E402

TEMPLATE = (
    Path(__file__).parent.parent
    / "ecoscope_workflows_ext_standard_patrol_events/data/standard_patrol_events.docx"
)
BLOCKS = [
    "personnel", "headline_stats", "time_density", "events_by_type",
    "category_priority", "events_bar", "monthly_stacked", "conclusions",
]  # fmt: skip
HEADINGS = [
    "Personnel", "Summary", "Patrol Effort", "Patrol Time Density", "Events by Type",
    "Events by Category and Priority", "Events Chart", "Events by Month",
    "Event Density", "Event Details", "Images", "Conclusions",
]  # fmt: skip
FOOTER = "This report was generated by Ecoscope using EarthRanger data"
NO_DATA = "NO-DATA-MARKER"


def _df():
    return pd.DataFrame({"a": ["x1", "x2"], "b": ["y1", "y2"]})


def _context(tmp_path, *, flags=None, effort=None, images_manual=False):
    png = tmp_path / "t.png"
    Image.new("RGB", (10, 10), "red").save(png)
    flags = {f"show_{b}": "true" for b in BLOCKS} | (flags or {})
    flags["show_images_manual"] = "true" if images_manual else "false"
    tr = TimeRange(
        since=datetime(2024, 1, 1),
        until=datetime(2024, 1, 31),
        timezone=TimezoneInfo(label="UTC", tzCode="UTC", name="UTC", utc_offset="+00:00"),
        time_format="%d %b %Y",
    )
    text = dict(
        title="TITLE", subtitle="SUBTITLE", area="AREA", generated_by="GENBY",
        date_generated="DATEGEN", n_patrols="11", total_km="22", total_hours="33",
        n_events="44", detail_intro="INTRO", no_data=NO_DATA, **flags,
    )  # fmt: skip
    items = [TextContextItem(key=k, value=v) for k, v in text.items()]
    items.append(TimeRangeContextItem(key="period", value=tr))
    for k in ("effort", "events_by_type", "category_priority", "personnel", "event_details"):
        items.append(TableContextItem(key=k, value=effort if k == "effort" and effort is not None else _df()))
    for k in ("tracks_map", "time_density_map", "events_bar", "monthly_stacked", "event_density_map"):
        items.append(ImageContextItem(key=k, value=str(png), width_inches=1))
    items.append(
        TableListContextItem(key="event_detail_tables", value=[{"heading": "HEAD1", "title": "TITLE1", "table": _df()}])
    )
    items.append(
        ImageListContextItem(key="images", value=pd.DataFrame({"caption": ["CAP1"], "image_path": [str(png)]}), width_inches=1)
    )
    return TemplateContext(items=items)


def _render(tmp_path, **kw):
    out = create_docx(str(TEMPLATE), _context(tmp_path, **kw), str(tmp_path / "out"))
    doc = Document(out)
    cells = [c.text for t in doc.tables for r in t.rows for c in r.cells]
    text = "\n".join([p.text for p in doc.paragraphs] + cells)
    return doc, text, "\n".join(p.text for p in doc.sections[0].footer.paragraphs)


def test_all_blocks_render(tmp_path):
    doc, text, footer = _render(tmp_path)
    for h in HEADINGS:
        assert h in text, h
    for s in ("TITLE", "SUBTITLE", "AREA", "GENBY", "DATEGEN", "01 Jan 2024", "11", "22", "33", "44",
              "INTRO", "HEAD1", "TITLE1", "x1", "y2", "CAP1"):  # fmt: skip
        assert s in text, s
    assert NO_DATA not in text
    assert FOOTER in footer
    assert "{%" not in text and "{{" not in text
    assert len(doc.inline_shapes) == 5 + 1  # five maps/charts + one list image


def test_skipped_block_and_empty_effort(tmp_path):
    _, text, _ = _render(tmp_path, flags={"show_time_density": "false"}, effort=pd.DataFrame(columns=["a", "b"]))
    assert "Patrol Time Density" not in text
    assert "Patrol Effort" in text
    assert NO_DATA in text


def test_images_manual_has_captions_and_empty_cells(tmp_path):
    doc, text, _ = _render(tmp_path, images_manual=True)
    assert "CAP1" in text
    assert len(doc.inline_shapes) == 5  # list image not rendered
