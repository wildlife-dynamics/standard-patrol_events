"""Builds the base standard patrol & events report template (docxtpl/Jinja).

Run in the ext-custom env (python-docx; the data package env does not have it):
  pixi run --manifest-path <task-library>/src/ecoscope-workflows-ext-custom/pyproject.toml \
      python .scripts/build_base_template.py

Partner templates are copies of this file with their own logos, title and labels.
Notes on docxtpl:
- `{%p ... %}` tags must sit alone in their own paragraph; `{%tr ... %}` alone in their own table row.
- show_<block> flags arrive as text (TextContextItem), so they are compared as strings:
  anything but "true"/"1" (case-insensitive, or a real bool True) is off.
"""

from pathlib import Path

from docx import Document
from docx.enum.table import WD_TABLE_ALIGNMENT

OUT = (
    Path(__file__).parent.parent
    / "src/ecoscope-workflows-ext-standard-patrol-events"
    / "ecoscope_workflows_ext_standard_patrol_events/data/standard_patrol_events.docx"
)
FOOTER = "This report was generated by Ecoscope using EarthRanger data"

doc = Document()


def tag(text):
    doc.add_paragraph(text)


def on(flag):
    return f"{{%p if {flag}|string|lower in ('true', '1') %}}"


def heading(text, level=1):
    doc.add_heading(text, level)


def dynamic_table(var):
    """Table with a dynamic number of columns, as in docxtpl's dynamic-column example.

    tc for/endfor tags each need their own cell; tr tags their own row.
    """
    t = doc.add_table(rows=4, cols=3)
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.rows[0].cells[0].text = f"{{%tc for col in {var}.col_labels %}}"
    t.rows[0].cells[1].text = "{{ col }}"
    t.rows[0].cells[2].text = "{%tc endfor %}"
    t.rows[1].cells[0].text = f"{{%tr for item in {var}.tbl_contents %}}"
    t.rows[2].cells[0].text = "{%tc for col in item.cols %}"
    t.rows[2].cells[1].text = "{{ col }}"
    t.rows[2].cells[2].text = "{%tc endfor %}"
    t.rows[3].cells[0].text = "{%tr endfor %}"
    return t


def data_block(var, render):
    """`var` is a table key; an empty/skipped table has no tbl_contents."""
    tag(f"{{%p if {var}.tbl_contents %}}")
    render()
    tag("{%p else %}")
    tag("{{ no_data }}")
    tag("{%p endif %}")


def image_block(var):
    tag(f"{{%p if {var} %}}")
    tag(f"{{{{ {var} }}}}")
    tag("{%p else %}")
    tag("{{ no_data }}")
    tag("{%p endif %}")


# --- metadata -------------------------------------------------------------
doc.add_heading("{{ title }}", 0)
doc.add_paragraph("{{ subtitle }}")
doc.add_paragraph("{{ area }}")
doc.add_paragraph("Reporting period: {{ period }}")
doc.add_paragraph("Generated by: {{ generated_by }}")
doc.add_paragraph("Date generated: {{ date_generated }}")

# --- personnel ------------------------------------------------------------
tag(on("show_personnel"))
heading("Personnel")
data_block("personnel", lambda: dynamic_table("personnel"))
tag("{%p endif %}")

# --- headline stats -------------------------------------------------------
tag(on("show_headline_stats"))
heading("Summary")
for label, key in [
    ("Patrols", "n_patrols"),
    ("Distance patrolled (km)", "total_km"),
    ("Patrol hours", "total_hours"),
    ("Events", "n_events"),
]:
    doc.add_paragraph(f"{label}: {{{{ {key} }}}}")
tag("{%p endif %}")

# --- patrol effort --------------------------------------------------------
heading("Patrol Effort")
data_block("effort", lambda: dynamic_table("effort"))
image_block("tracks_map")

tag(on("show_time_density"))
heading("Patrol Time Density")
image_block("time_density_map")
tag("{%p endif %}")

# --- event summary --------------------------------------------------------
tag(on("show_events_by_type"))
heading("Events by Type")
data_block("events_by_type", lambda: dynamic_table("events_by_type"))
tag("{%p endif %}")

tag(on("show_category_priority"))
heading("Events by Category and Priority")
data_block("category_priority", lambda: dynamic_table("category_priority"))
tag("{%p endif %}")

tag(on("show_events_bar"))
heading("Events Chart")
image_block("events_bar")
tag("{%p endif %}")

tag(on("show_monthly_stacked"))
heading("Events by Month")
image_block("monthly_stacked")
tag("{%p endif %}")

heading("Event Density")
image_block("event_density_map")

# --- event details --------------------------------------------------------
heading("Event Details")
doc.add_paragraph("{{ detail_intro }}")
tag("{%p if event_details.tbl_contents or event_detail_tables %}")
tag("{%p if event_details.tbl_contents %}")
dynamic_table("event_details")
tag("{%p endif %}")
tag("{%p for t in event_detail_tables %}")
doc.add_heading("{{ t.heading }}", 2)
doc.add_paragraph("{{ t.title }}")
dynamic_table("t")
tag("{%p endfor %}")
tag("{%p else %}")
tag("{{ no_data }}")
tag("{%p endif %}")

# --- images ---------------------------------------------------------------
heading("Images")
tag("{%p if show_images_manual|string|lower in ('true', '1') %}")
t = doc.add_table(rows=3, cols=2)
t.style = "Table Grid"
t.rows[0].cells[0].text = "Photo"
t.rows[0].cells[1].text = "Caption"
t.rows[1].cells[0].text = "{%tr for img in images %}"
t.rows[2].cells[1].text = "{{ img.caption }}"
t.add_row().cells[0].text = "{%tr endfor %}"
tag("{%p elif images %}")
tag("{%p for img in images %}")
tag("{{ img.caption }}")
tag("{{ img.image }}")
tag("{%p endfor %}")
tag("{%p else %}")
tag("{{ no_data }}")
tag("{%p endif %}")

# --- conclusions ----------------------------------------------------------
tag(on("show_conclusions"))
heading("Conclusions")
doc.add_paragraph("")
tag("{%p endif %}")

doc.sections[0].footer.paragraphs[0].text = FOOTER

OUT.parent.mkdir(parents=True, exist_ok=True)
doc.save(OUT)
print(f"wrote {OUT}")
